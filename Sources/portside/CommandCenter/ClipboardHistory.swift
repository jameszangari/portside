/// One copied text and when it was copied. Nothing else is kept: no source
/// app, no type list, no window title.
struct ClipboardEntry: Codable, Equatable, Identifiable, Sendable {
    var id: UUID
    var text: String
    var date: Date

    init(id: UUID = UUID(), text: String, date: Date) {
        self.id = id
        self.text = text
        self.date = date
    }

    /// The first non-blank line, cut for a row title.
    var title: String {
        let line = text.split(whereSeparator: \.isNewline).map { $0.trimmingCharacters(in: .whitespaces) }.first { !$0.isEmpty } ?? ""
        return line.count <= 100 ? line : String(line.prefix(99)) + "…"
    }
}

/// Settings for clipboard history (`command-center-clipboard-prefs.json`).
/// Not private: no copied text is in it.
struct ClipboardPrefs: Codable, Equatable, Sendable {
    static let expiryChoices = [1, 24, 24 * 7, 24 * 30]
    static let userAppLimit = 50

    var paused = false
    /// Bundle IDs the person excluded, on top of the built-in list.
    var excludedApps: [String] = []
    var expiryHours = 24

    init() {}

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        paused = (try? c.decodeIfPresent(Bool.self, forKey: .paused)) ?? false
        let apps = (try? c.decodeIfPresent([String].self, forKey: .excludedApps)) ?? []
        excludedApps = Array(apps.filter(ClipboardPolicy.isBundleID).prefix(Self.userAppLimit))
        let hours = (try? c.decodeIfPresent(Int.self, forKey: .expiryHours)) ?? 24
        expiryHours = Self.expiryChoices.contains(hours) ? hours : 24
    }
}

/// What may be kept. Pure functions, so every rule is testable. None of this
/// can recognize every secret: it refuses what apps mark as sensitive, what
/// comes from apps the person or Portside excluded, and what is copied while
/// macOS says a password field has the keyboard.
enum ClipboardPolicy {
    static let maxCharacters = 20_000
    static let maxEntries = 100

    /// Types apps put on the pasteboard to say "do not keep this"
    /// (nspasteboard.org and password manager conventions).
    static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "com.apple.is-remote-clipboard",
    ]

    /// Never captured from these, whatever the person chose. Matched as a
    /// bundle ID or a prefix of one that ends at a dot.
    static let builtInExcludedApps: [String] = [
        "com.apple.keychainaccess", "com.apple.Passwords", "com.1password", "com.agilebits.onepassword",
        "com.bitwarden.desktop", "com.lastpass", "org.keepassxc.keepassxc", "com.dashlane", "com.nordpass",
        "me.proton.pass", "com.apple.systempreferences",
    ]

    enum Skip: Equatable {
        case paused, secureInput, sensitiveType, excludedApp, filePayload, noText, blank, tooLarge
    }

    enum Decision: Equatable {
        case capture(String)
        case skip(Skip)
    }

    static func isBundleID(_ text: String) -> Bool {
        !text.isEmpty && text.count <= 200 && text.allSatisfy { $0.isASCII && ($0.isLetter || $0.isNumber || $0 == "." || $0 == "-" || $0 == "_") }
    }

    static func isExcluded(_ bundleID: String?, user: [String]) -> Bool {
        guard let bundleID else { return false }
        let lowered = bundleID.lowercased()
        func matches(_ rule: String) -> Bool {
            let rule = rule.lowercased()
            return lowered == rule || lowered.hasPrefix(rule + ".")
        }
        return builtInExcludedApps.contains(where: matches) || user.contains(where: matches)
    }

    /// `apps` are the frontmost app now and at the previous look, so a copy
    /// made just before the app changed is judged by both.
    static func decide(
        types: [String], text: String?, apps: [String?], user: [String], paused: Bool, secureInput: Bool
    ) -> Decision {
        if paused { return .skip(.paused) }
        if secureInput { return .skip(.secureInput) }
        if types.contains(where: sensitiveTypes.contains) { return .skip(.sensitiveType) }
        if apps.contains(where: { isExcluded($0, user: user) }) { return .skip(.excludedApp) }
        if types.contains("public.file-url") { return .skip(.filePayload) }
        guard let text else { return .skip(.noText) }
        if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return .skip(.blank) }
        if text.count > maxCharacters { return .skip(.tooLarge) }
        return .capture(text)
    }

    /// Newest first, bounded, with entries past the expiry dropped.
    static func pruned(_ entries: [ClipboardEntry], now: Date, expiryHours: Int) -> [ClipboardEntry] {
        let cutoff = now.addingTimeInterval(-Double(expiryHours) * 3600)
        return Array(entries.filter { $0.date > cutoff }.sorted { $0.date > $1.date }.prefix(maxEntries))
    }
}

// MARK: - Sources

@MainActor
protocol PasteboardAccess: AnyObject {
    var changeCount: Int { get }
    var types: [String] { get }
    var string: String? { get }
    /// Replaces the contents with text. Returns the new change count.
    func write(_ text: String) -> Int?
}

@MainActor
final class SystemPasteboard: PasteboardAccess {
    private let board = NSPasteboard.general
    var changeCount: Int { board.changeCount }
    var types: [String] { (board.types ?? []).map(\.rawValue) }
    var string: String? { board.string(forType: .string) }

    func write(_ text: String) -> Int? {
        board.clearContents()
        return board.setString(text, forType: .string) ? board.changeCount : nil
    }
}

/// Where the history's encryption key lives. A random key in the login
/// keychain, readable only on this Mac while unlocked and never in a backup.
protocol ClipboardKeyStore: Sendable {
    func key() throws -> SymmetricKey
}

struct KeychainKeyStore: ClipboardKeyStore {
    struct Failure: Error, LocalizedError {
        var errorDescription: String? { "Portside could not use the keychain to protect the history, so it stays off." }
    }

    var service = "com.james.portside.clipboard-history"
    var account = "key"

    func key() throws -> SymmetricKey {
        var query: [String: Any] = [kSecClass as String: kSecClassGenericPassword, kSecAttrService as String: service, kSecAttrAccount as String: account]
        var found: CFTypeRef?
        let read = SecItemCopyMatching(query.merging([kSecReturnData as String: true, kSecMatchLimit as String: kSecMatchLimitOne]) { $1 } as CFDictionary, &found)
        if read == errSecSuccess, let data = found as? Data, data.count == 32 { return SymmetricKey(data: data) }
        guard read == errSecItemNotFound || read == errSecSuccess else { throw Failure() }
        // A wrong-sized or unreadable old item is replaced.
        SecItemDelete(query as CFDictionary)
        var bytes = [UInt8](repeating: 0, count: 32)
        guard SecRandomCopyBytes(kSecRandomDefault, bytes.count, &bytes) == errSecSuccess else { throw Failure() }
        query[kSecValueData as String] = Data(bytes)
        query[kSecAttrAccessible as String] = kSecAttrAccessibleWhenUnlockedThisDeviceOnly
        guard SecItemAdd(query as CFDictionary, nil) == errSecSuccess else { throw Failure() }
        return SymmetricKey(data: bytes)
    }

    func delete() {
        SecItemDelete([kSecClass as String: kSecClassGenericPassword, kSecAttrService as String: service, kSecAttrAccount as String: account] as CFDictionary)
    }
}

// MARK: - Encrypted file

/// The history on disk: AES-GCM sealed JSON, mode 0600, excluded from
/// backups. The file never holds readable text; the key is not in the file.
struct ClipboardFile {
    static let magic = Data("PSCB1".utf8)

    let url: URL
    let keys: ClipboardKeyStore

    static var defaultURL: URL {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
        return base.appendingPathComponent("com.james.portside").appendingPathComponent("command-center-clipboard.bin")
    }

    /// Empty for a missing, truncated, tampered or foreign file.
    func read() -> [ClipboardEntry] {
        guard let data = try? Data(contentsOf: url), data.starts(with: Self.magic),
              let key = try? keys.key(),
              let box = try? AES.GCM.SealedBox(combined: data.dropFirst(Self.magic.count)),
              let plain = try? AES.GCM.open(box, using: key, authenticating: Self.magic),
              let entries = try? JSONDecoder().decode([ClipboardEntry].self, from: plain) else { return [] }
        return entries
    }

    func write(_ entries: [ClipboardEntry]) throws {
        let key = try keys.key()
        let plain = try JSONEncoder().encode(entries)
        let sealed = try AES.GCM.seal(plain, using: key, authenticating: Self.magic)
        guard let combined = sealed.combined else { throw CocoaError(.fileWriteUnknown) }
        let data = Self.magic + combined
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        let temp = url.deletingLastPathComponent().appendingPathComponent(".clipboard-\(UUID().uuidString).tmp")
        guard FileManager.default.createFile(atPath: temp.path, contents: data, attributes: [.posixPermissions: 0o600]) else {
            throw CocoaError(.fileWriteUnknown)
        }
        do {
            var values = URLResourceValues()
            values.isExcludedFromBackup = true
            var tempURL = temp
            try tempURL.setResourceValues(values)
            _ = try FileManager.default.replaceItemAt(url, withItemAt: temp)
        } catch {
            try? FileManager.default.removeItem(at: temp)
            throw error
        }
    }

    func delete() {
        try? FileManager.default.removeItem(at: url)
    }
}

// MARK: - Service

/// Opt-in text clipboard history (P2-CMD-04). Runs only while the
/// `clipboard` module does: one timer that compares `changeCount` (macOS has
/// no pasteboard change notification) every 0.75 s, stopped while paused or
/// off; it is not in the dock reveal path. A change is judged by
/// `ClipboardPolicy` and, if kept, written encrypted. Whatever the verdict,
/// the change is consumed, so a skipped copy can never be captured later
/// (when secure input ends, or the frontmost app changes).
@MainActor
final class ClipboardService: ObservableObject {
    static let shared = ClipboardService(file: ClipboardFile(url: ClipboardFile.defaultURL, keys: KeychainKeyStore()),
                                         prefsURL: ClipboardService.defaultPrefsURL)

    static let interval: TimeInterval = 0.75

    @Published private(set) var entries: [ClipboardEntry] = []
    @Published private(set) var prefs = ClipboardPrefs()
    /// The `clipboard` module runs.
    @Published private(set) var isActive = false
    /// Runs after any change to the entries (Command Center re-reads).
    var onChange: (@MainActor () -> Void)?

    private let file: ClipboardFile
    private let prefsURL: URL?
    private let pasteboard: any PasteboardAccess
    private let frontmost: @MainActor () -> String?
    private let secureInput: @MainActor () -> Bool
    private let now: @MainActor () -> Date
    private let startsTimer: Bool
    private var lastCount = 0
    private var ownCount: Int?
    private var previousFront: String?
    private var timer: DispatchSourceTimer?
    private let logger = Logger(subsystem: "com.james.portside", category: "CommandCenter")

    init(
        file: ClipboardFile,
        prefsURL: URL?,
        pasteboard: (any PasteboardAccess)? = nil,
        frontmost: @escaping @MainActor () -> String? = { NSWorkspace.shared.frontmostApplication?.bundleIdentifier },
        secureInput: @escaping @MainActor () -> Bool = { IsSecureEventInputEnabled() },
        now: @escaping @MainActor () -> Date = Date.init,
        startsTimer: Bool = true
    ) {
        self.file = file
        self.prefsURL = prefsURL
        self.pasteboard = pasteboard ?? SystemPasteboard()
        self.frontmost = frontmost
        self.secureInput = secureInput
        self.now = now
        self.startsTimer = startsTimer
        prefs = prefsURL.flatMap(Self.readPrefs) ?? ClipboardPrefs()
    }

    nonisolated static var defaultPrefsURL: URL {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
        return base.appendingPathComponent("com.james.portside").appendingPathComponent("command-center-clipboard-prefs.json")
    }

    var unavailableReason: String? { isActive ? nil : "Clipboard History is turned off." }

    // MARK: Lifecycle

    /// Loads the history (which needs the key, so a keychain refusal keeps
    /// the module off) and starts watching unless paused. What is on the
    /// pasteboard now is never captured.
    func activate() throws {
        _ = try file.keys.key()
        isActive = true
        entries = ClipboardPolicy.pruned(file.read(), now: now(), expiryHours: prefs.expiryHours)
        baseline()
        startTimerIfNeeded()
        onChange?()
    }

    /// Stops watching and drops the entries from memory. The encrypted file
    /// stays until it expires or is cleared.
    func deactivate() {
        isActive = false
        stopTimer()
        entries = []
        ownCount = nil
        onChange?()
    }

    private func baseline() {
        lastCount = pasteboard.changeCount
        previousFront = frontmost()
    }

    // MARK: Watching

    private func startTimerIfNeeded() {
        stopTimer()
        guard startsTimer, isActive, !prefs.paused else { return }
        let source = DispatchSource.makeTimerSource(queue: .main)
        source.schedule(deadline: .now() + Self.interval, repeating: Self.interval, leeway: .milliseconds(250))
        source.setEventHandler { [weak self] in
            MainActor.assumeIsolated { self?.tick() }
        }
        source.resume()
        timer = source
    }

    private func stopTimer() {
        timer?.cancel()
        timer = nil
    }

    /// One look at the pasteboard. Public for tests; the timer calls it.
    func tick() {
        guard isActive, !prefs.paused else { return }
        let count = pasteboard.changeCount
        let front = frontmost()
        defer {
            lastCount = count
            previousFront = front
        }
        guard count != lastCount else { return }
        if count == ownCount {
            ownCount = nil
            return
        }
        let decision = ClipboardPolicy.decide(
            types: pasteboard.types, text: pasteboard.string, apps: [front, previousFront],
            user: prefs.excludedApps, paused: prefs.paused, secureInput: secureInput()
        )
        guard case .capture(let text) = decision else { return }
        record(text)
    }

    private func record(_ text: String) {
        let date = now()
        var kept = entries.filter { $0.text != text }
        kept.insert(ClipboardEntry(text: text, date: date), at: 0)
        entries = ClipboardPolicy.pruned(kept, now: date, expiryHours: prefs.expiryHours)
        persist()
        onChange?()
    }

    /// Portside wrote this change itself (a copy from history, a snippet, a
    /// calculator result): not captured again.
    func noteOwnWrite(changeCount: Int) {
        ownCount = changeCount
    }

    // MARK: Actions

    func entry(_ id: UUID) -> ClipboardEntry? { entries.first { $0.id == id } }

    /// Puts an entry's text on the pasteboard. Nothing is pasted.
    func copy(_ id: UUID) -> Result<String?, CommandFailure> {
        if let reason = unavailableReason { return .failure(CommandFailure(reason: reason)) }
        guard let entry = entry(id) else { return .failure(CommandFailure(reason: "That entry has expired or was deleted.")) }
        guard let count = pasteboard.write(entry.text) else { return .failure(CommandFailure(reason: "macOS would not take the text.")) }
        ownCount = count
        return .success(nil)
    }

    func delete(_ id: UUID) -> Result<String?, CommandFailure> {
        if let reason = unavailableReason { return .failure(CommandFailure(reason: reason)) }
        guard entries.contains(where: { $0.id == id }) else { return .failure(CommandFailure(reason: "That entry is already gone.")) }
        entries.removeAll { $0.id == id }
        persist()
        onChange?()
        return .success("Deleted.")
    }

    /// Deletes every entry and the file.
    func clear() {
        entries = []
        file.delete()
        onChange?()
    }

    // MARK: Preferences

    func setPaused(_ paused: Bool) {
        guard prefs.paused != paused else { return }
        prefs.paused = paused
        savePrefs()
        if paused {
            stopTimer()
        } else if isActive {
            // Copies made while paused are never captured.
            baseline()
            startTimerIfNeeded()
        }
    }

    func setExpiry(hours: Int) {
        guard ClipboardPrefs.expiryChoices.contains(hours), prefs.expiryHours != hours else { return }
        prefs.expiryHours = hours
        savePrefs()
        prune()
    }

    func excludeApp(_ bundleID: String) -> Bool {
        guard ClipboardPolicy.isBundleID(bundleID), !prefs.excludedApps.contains(bundleID),
              prefs.excludedApps.count < ClipboardPrefs.userAppLimit else { return false }
        prefs.excludedApps.append(bundleID)
        savePrefs()
        return true
    }

    func includeApp(_ bundleID: String) {
        prefs.excludedApps.removeAll { $0 == bundleID }
        savePrefs()
    }

    /// Drops expired entries now (on open, on a change of expiry).
    func prune() {
        guard isActive else { return }
        let kept = ClipboardPolicy.pruned(entries, now: now(), expiryHours: prefs.expiryHours)
        guard kept != entries else { return }
        entries = kept
        persist()
        onChange?()
    }

    // MARK: Query

    /// `clip` or `clipboard` as the first word, then optional words that
    /// must all be in the text. nil for any other query, so ordinary
    /// searches never show copied text.
    static func filter(in query: String) -> String? {
        let trimmed = query.trimmingCharacters(in: .whitespacesAndNewlines)
        let lowered = trimmed.lowercased()
        for word in ["clipboard", "clip"] {
            if lowered == word { return "" }
            if lowered.hasPrefix(word + " ") { return String(trimmed.dropFirst(word.count + 1)) }
        }
        return nil
    }

    static let resultLimit = 8

    func results(for query: String) -> [ClipboardEntry] {
        guard isActive, let text = Self.filter(in: query) else { return [] }
        prune()
        let terms = CommandCenterRanker.terms(text)
        let matching = terms.isEmpty ? entries : entries.filter { entry in
            let folded = CommandCenterRanker.normalize(entry.text)
            return terms.allSatisfy(folded.contains)
        }
        return Array(matching.prefix(Self.resultLimit))
    }

    // MARK: Files

    private func persist() {
        do {
            try file.write(entries)
        } catch {
            // The error never carries copied text.
            logger.error("clipboard history not saved: \(error.localizedDescription, privacy: .public)")
        }
    }

    private static func readPrefs(_ url: URL) -> ClipboardPrefs? {
        guard let data = try? Data(contentsOf: url) else { return nil }
        return try? JSONDecoder().decode(ClipboardPrefs.self, from: data)
    }

    private func savePrefs() {
        guard let prefsURL else { return }
        do {
            let encoder = JSONEncoder()
            encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
            try FileManager.default.createDirectory(at: prefsURL.deletingLastPathComponent(), withIntermediateDirectories: true)
            try encoder.encode(prefs).write(to: prefsURL, options: .atomic)
        } catch {
            logger.error("clipboard preferences not saved: \(error.localizedDescription, privacy: .public)")
        }
    }
}

// MARK: - Module

/// The optional `clipboard` module. Off by default and held off by
/// restricted mode (it watches the pasteboard). Without a usable keychain it
/// fails to start with a reason, rather than keep history unprotected.
@MainActor
final class ClipboardModule: PortsideModule {
    static let moduleID = ModuleID("clipboard")!
    static let copyCommand = CommandID("clipboard.copy")!
    static let deleteCommand = CommandID("clipboard.delete")!
    static let clearCommand = CommandID("clipboard.clear")!
    static let pauseCommand = CommandID("clipboard.pause")!
    static let resumeCommand = CommandID("clipboard.resume")!

    let id = ClipboardModule.moduleID
    let title = "Clipboard History"
    let summary = "Keeps the text you copy, for a day by default, so Command Center can find it again: type clip, or clip and some words. Encrypted on this Mac with a key in your keychain, never synced or sent anywhere. It skips what apps mark as secret, password managers and the apps you exclude, and anything copied while a password field has the keyboard, but it cannot recognize every secret. Pause, expiry and Clear History are in Settings > General > Command Center. Text only, no images or files."
    let fallback = "Copying and pasting work the same without it."
    let dependencies: [ModuleDependency] = [.module(CommandCenterModule.moduleID)]

    let service: ClipboardService

    init(service: ClipboardService) {
        self.service = service
    }

    func commands() -> [CommandDescriptor] {
        let idInput = CommandInputSchema.string(maxLength: 36)
        return [
            CommandDescriptor(
                id: Self.copyCommand, title: "Copy Clipboard Entry", symbolName: "doc.on.clipboard", input: idInput,
                handler: { [service] input in
                    guard case .string(let raw) = input, let id = UUID(uuidString: raw) else { return .failure(CommandFailure(reason: "No entry given.")) }
                    return service.copy(id)
                }
            ),
            CommandDescriptor(
                id: Self.deleteCommand, title: "Delete Clipboard Entry", symbolName: "trash", input: idInput,
                handler: { [service] input in
                    guard case .string(let raw) = input, let id = UUID(uuidString: raw) else { return .failure(CommandFailure(reason: "No entry given.")) }
                    return service.delete(id)
                }
            ),
            CommandDescriptor(
                id: Self.clearCommand, title: "Clear Clipboard History", keywords: ["clipboard", "history", "delete"], symbolName: "trash",
                unavailableReason: { [service] in service.unavailableReason },
                handler: { [service] _ in
                    service.clear()
                    return .success("Clipboard history cleared.")
                }
            ),
            CommandDescriptor(
                id: Self.pauseCommand, title: "Pause Clipboard History", keywords: ["clipboard", "stop"], symbolName: "pause.circle",
                unavailableReason: { [service] in service.unavailableReason ?? (service.prefs.paused ? "Clipboard history is already paused." : nil) },
                handler: { [service] _ in
                    service.setPaused(true)
                    return .success("Clipboard history paused.")
                }
            ),
            CommandDescriptor(
                id: Self.resumeCommand, title: "Resume Clipboard History", keywords: ["clipboard", "start"], symbolName: "play.circle",
                unavailableReason: { [service] in service.unavailableReason ?? (service.prefs.paused ? nil : "Clipboard history is not paused.") },
                handler: { [service] _ in
                    service.setPaused(false)
                    return .success("Clipboard history resumed.")
                }
            ),
        ]
    }

    func start(_ context: ModuleContext) throws {
        try service.activate()
        context.onStop { [service] in
            MainActor.assumeIsolated { service.deactivate() }
        }
    }
}
